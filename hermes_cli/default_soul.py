def _normalize(text: str) -> str:
    """Normalize file content for legacy-template comparison."""
    return text.replace("\r\n", "\n").replace("\r", "\n").lstrip("\ufeff").strip()


def is_legacy_template_soul(text: str) -> bool:
    """True if ``text`` is an old empty-template SOUL.md (no user persona).

    Older installers seeded a comment-only scaffold or a Nous-branded
    identity string instead of the Evil-Hermes default. Any file matching
    one of those known scaffolds carries zero user intent and is safe to
    upgrade in place. Any deviation (the user typed a persona, even one
    character outside the template) makes this return False.
    """
    normalized = _normalize(text)
    return any(normalized == _normalize(t) for t in _LEGACY_TEMPLATE_SOULS)


def is_legacy_template_user(text: str) -> bool:
    """True if ``text`` is an old empty-template USER.md (no operator persona)."""
    normalized = _normalize(text)
    return any(normalized == _normalize(t) for t in _LEGACY_TEMPLATE_USERS)


def is_legacy_template_memory(text: str) -> bool:
    """True if ``text`` is an old empty-template MEMORY.md (no agent memory)."""
    normalized = _normalize(text)
    return any(normalized == _normalize(t) for t in _LEGACY_TEMPLATE_MEMORIES)
